// Generates src/app/fileIcons.generated.ts from Material Icon Theme (MIT,
// https://github.com/material-extensions/vscode-material-icon-theme) via @iconify-json/material-icon-theme.
// Only the icons mapped below are emitted. Usage: node scripts/gen-file-icons.mjs
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'

const require = createRequire(import.meta.url)
const set = require('@iconify-json/material-icon-theme/icons.json')
const { version } = require('@iconify-json/material-icon-theme/package.json')

/** FileKind (src/domain/fileKind.ts) → Material Icon Theme icon name. */
const MAP = {
  folder: 'folder-base', 'folder-video': 'folder-video', 'folder-audio': 'folder-audio', 'folder-images': 'folder-images',
  'folder-archive': 'folder-archive', video: 'video', audio: 'audio', image: 'image', vector: 'svg', archive: 'zip',
  disc: 'disc', cue: 'cue', vm: 'virtual', installer: 'exe', library: 'dll', android: 'android', package: 'lib',
  pdf: 'pdf', ebook: 'epub', document: 'word', spreadsheet: 'table', slides: 'powerpoint', subtitle: 'subtitles',
  font: 'font', json: 'json', xml: 'xml', yaml: 'yaml', html: 'html', markdown: 'markdown', log: 'log', shell: 'console',
  powershell: 'powershell', python: 'python', javascript: 'javascript', code: 'console', text: 'document', readme: 'readme',
  license: 'license', checksum: 'lock', signature: 'key', certificate: 'certificate', database: 'database', model3d: '3d',
  torrent: 'document', file: 'document',
}

const out = {}
for (const [kind, name] of Object.entries(MAP)) {
  const icon = set.icons[name]
  if (!icon) throw new Error(`Material icon "${name}" not found for kind "${kind}"`)
  out[kind] = { body: icon.body, w: icon.width ?? set.width ?? 16, h: icon.height ?? set.height ?? 16 }
}
const header = `// GENERATED by scripts/gen-file-icons.mjs from @iconify-json/material-icon-theme@${version} (MIT). Do not edit.\n`
writeFileSync(
  new URL('../src/app/fileIcons.generated.ts', import.meta.url),
  `${header}import type { FileKind } from '@/domain/fileKind'\n\nexport const FILE_ICONS: Record<FileKind, { body: string; w: number; h: number }> = ${JSON.stringify(out, null, 2)}\n`,
)
console.log(`Wrote ${Object.keys(out).length} file icons`)
